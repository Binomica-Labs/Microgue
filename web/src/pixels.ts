// Pixel art. Each sprite is a 16x16 grid of ROLE indices, not colours, so the
// organism's own pigment still tints it and every sprite stays a block of
// editable text in version control.
//
//   .  transparent
//   1  dark      (organelles, septa, chloroplast, capsule)
//   2  body      (the pigment itself)
//   3  accent    (flagella, pili, lighter membrane)
//   4  hi        (sulfur globules, chlorosomes, granules, highlights)
//
// These were seeded by rasterising the vector morphologies in shapes.ts, so
// they start diagnostically correct. Edit them freely -- a row is just a
// string, and PX_SIZE rows of PX_SIZE characters is the only invariant.

