/** A sprite is valid when it is PX_SIZE rows of PX_SIZE legal characters. */
export function validate(s: PixelSprite): string | null {
  if (s.length !== PX_SIZE) return `expected ${PX_SIZE} rows, got ${s.length}`;
  for (let y = 0; y < s.length; y++) {
    const row = s[y];
    if (row === undefined) return `row ${y} missing`;
    if (row.length !== PX_SIZE) return `row ${y} is ${row.length} wide`;
    for (const ch of row) {
      if (!".1234".includes(ch)) return `row ${y} has illegal character '${ch}'`;
    }
  }
  return null;
}
